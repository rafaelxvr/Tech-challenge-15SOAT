package com.oficina.saga.domain;

public enum EstadoSaga {
    AGUARDANDO_DIAGNOSTICO, AGUARDANDO_ORCAMENTO, AGUARDANDO_DECISAO, AGUARDANDO_PAGAMENTO,
    RESERVANDO_PECAS, AGUARDANDO_REPARO, EM_EXECUCAO, CONCLUIDA, COMPENSANDO, CANCELADA, FALHA_COMPENSACAO;

    public boolean terminal() { return this == CONCLUIDA || this == CANCELADA || this == FALHA_COMPENSACAO; }
}
